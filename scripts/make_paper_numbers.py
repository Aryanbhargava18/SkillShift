"""Generate paper/numbers.tex: every \newcommand macro the paper uses, from results/*.json.

Run: uv run python scripts/make_paper_numbers.py
No number in paper/*.tex is typed by hand; they all resolve to macros defined here.

A macro whose source result file does not exist yet resolves to a visible
\PENDING marker, so the paper always compiles and missing numbers are obvious.
Light I/O only (reads small JSONs) — safe to run while a model is training.
"""

import json
from pathlib import Path

R = Path("results")
OUT = Path("paper/numbers.tex")

# Dataset / split constants. Source of record is results/data_summary.json (written
# by scripts/data_summary.py); these fallbacks match MaliciousSkillBench (arXiv 2608.19901)
# and NOTES.md and are used only until that file exists, so the paper still compiles.
DATA_FALLBACK = {
    "skills": 9740, "malicious": 7505, "benign": 2235,
    "test_benign": 545, "test_atr_benign": 455,
}


def load(name):
    p = R / name
    return json.loads(p.read_text()) if p.exists() else None


def pct(x, nd=1):
    return f"{100 * x:.{nd}f}\\%"


def macro(name, value):
    return f"\\newcommand{{\\{name}}}{{{value}}}"


def main() -> None:
    lines = [
        "% Generated by scripts/make_paper_numbers.py. Do not edit by hand.",
        "\\newcommand{\\PENDING}{\\textbf{[pending]}}",
        "",
    ]
    m = {}

    base = load("baselines.json")
    if base:
        sd = base["source_disjoint"]["tfidf_svm"]
        m["RandomSvmFone"] = f"{base['random']['tfidf_svm']['macro_f1']:.3f}"
        m["SourceSvmFone"] = f"{sd['macro_f1']:.3f}"
        m["SourceSvmFpr"] = pct(sd["benign_fpr"], 0)

    probe = load("shortcut_probe.json")
    if probe:
        s = probe["source_id"]
        m["ProbeAcc"] = pct(s["accuracy"])
        m["ProbeSources"] = str(s["n_sources"])

    # Headline fix: prefer mechanism.json (has bootstrap CIs); fall back to robust_classical.
    mech = load("mechanism.json")
    rob = load("robust_classical.json")
    if mech and "runs" in mech:
        all_r, mix_r = mech["runs"]["all"]["default"], mech["runs"]["mixed_only"]["default"]
        m["FprAll"] = pct(all_r["benign_fpr"], 0)
        m["FprMixed"] = pct(mix_r["benign_fpr"])
        m["PrAll"] = f"{all_r['pr_auc']:.2f}"
        m["PrMixed"] = f"{mix_r['pr_auc']:.2f}"
        sm = mech.get("size_matched_mixed_mean")
        if sm:
            m["FprSizeMatched"] = pct(sm["benign_fpr"], 0)
        ci = mech.get("bootstrap", {}).get("benign_fpr_at_0.5", {}).get("mixed_only")
        if ci:
            m["FprMixedCI"] = f"[{pct(ci[1])}, {pct(ci[2])}]"
        pr = mech.get("pairing", {})
        by = pr.get("by_source", {})
        m["MixedSkillTrustBench"] = str(by.get("SkillTrustBench", "?"))
        m["MixedAgentTrap"] = str(by.get("AgentTrap", "?"))
        m["MixedSkillTrojan"] = str(by.get("SkillTrojan", "?"))
        m["MechanismSentence"] = mechanism_sentence(mech)
        m["ConclusionMechanism"] = conclusion_sentence(mech)
    elif rob:
        m["FprAll"] = pct(rob["all/word_lr"]["default"]["benign_fpr"], 0)
        m["FprMixed"] = pct(rob["mixed_only/word_lr"]["default"]["benign_fpr"])
        m["PrAll"] = f"{rob['all/word_lr']['default']['pr_auc']:.2f}"
        m["PrMixed"] = f"{rob['mixed_only/word_lr']['default']['pr_auc']:.2f}"
        sms = [rob[f"size_matched_s{i}/word_lr"]["default"]["benign_fpr"] for i in range(3)
               if f"size_matched_s{i}/word_lr" in rob]
        if sms:
            m["FprSizeMatched"] = pct(sum(sms) / len(sms), 0)

    cmp = load("compare_models.json")
    if cmp:
        m["TransformerSentence"] = transformer_sentence(cmp)

    ev = load("adv_evasion.json")
    if ev:
        ma, mm = ev["models"]["all"], ev["models"]["mixed_only"]
        m["EvasionK"] = str(ev["headline_k"])
        m["EvasionAsrAll"] = pct(ma["asr_benign_at_k"], 0)
        m["EvasionControlAll"] = pct(ma["asr_random_at_k"], 0)
        m["EvasionAsrMixed"] = pct(mm["asr_benign_at_k"], 0)
        m["EvasionGapAll"] = pct(ma["source_specific_gap"], 0)

    ds = load("data_summary.json") or DATA_FALLBACK
    m["DataSkills"] = f"{ds['skills']:,}"
    m["DataMalicious"] = f"{ds['malicious']:,}"
    m["DataBenign"] = f"{ds['benign']:,}"
    m["TestBenign"] = str(ds["test_benign"])
    m["TestAtrBenign"] = str(ds["test_atr_benign"])

    needed = [
        "DataSkills", "DataMalicious", "DataBenign", "TestBenign", "TestAtrBenign",
        "RandomSvmFone", "SourceSvmFone", "SourceSvmFpr", "ProbeAcc", "ProbeSources",
        "FprAll", "FprMixed", "FprMixedCI", "PrAll", "PrMixed", "FprSizeMatched",
        "MixedSkillTrustBench", "MixedAgentTrap", "MixedSkillTrojan",
        "MechanismSentence", "TransformerSentence", "ConclusionMechanism",
        "EvasionK", "EvasionAsrAll", "EvasionControlAll", "EvasionAsrMixed", "EvasionGapAll",
    ]
    pending = [n for n in needed if n not in m]
    for n in needed:
        lines.append(macro(n, m.get(n, "\\PENDING")))

    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} with {len(needed) - len(pending)}/{len(needed)} macros filled")
    if pending:
        print("pending (result file not ready):", ", ".join(pending))


def mechanism_sentence(mech):
    pr = mech.get("pairing", {})
    bp = mech.get("break_pairs_mean", {})
    sm = mech.get("size_matched_mixed_mean", {})
    if not (bp and sm):
        return "\\PENDING"
    twin = pr.get("malicious_with_benign_twin", 0)
    mal = pr.get("malicious", 1)
    share = pct(twin / mal, 0) if mal else "?"
    bp_fpr, sm_fpr = bp["benign_fpr"], sm["benign_fpr"]
    if bp_fpr > sm_fpr + 0.1:
        verdict = (f"breaking the pairs raises the benign false-positive rate to {pct(bp_fpr, 0)} "
                   f"while a size-matched control that leaves pairs intact stays at {pct(sm_fpr, 0)}, "
                   f"so the gain comes from the minimal-pair construction, not label mixing alone")
    else:
        verdict = (f"breaking the pairs leaves the benign false-positive rate at {pct(bp_fpr, 0)}, "
                   f"close to the {pct(sm_fpr, 0)} of a size-matched control, so label mixing within a "
                   f"source\\,---\\,not the pairing itself\\,---\\,drives the gain")
    return (f"In these sources {share} of malicious skills are injected copies of a benign skill; "
            f"{verdict}.")


def conclusion_sentence(mech):
    bp = mech.get("break_pairs_mean", {})
    sm = mech.get("size_matched_mixed_mean", {})
    if not (bp and sm):
        return "\\PENDING"
    if bp["benign_fpr"] > sm["benign_fpr"] + 0.1:
        return ("The remaining caution is that, on this benchmark, the fix leans on minimal-pair "
                "construction rather than label mixing alone, so it should be retested on skills "
                "written independently of their benign twins.")
    return ("On this benchmark the gain survives breaking the benign--malicious pairs, so it rests "
            "on label mixing within a source rather than on paired construction.")


def transformer_sentence(cmp):
    f = cmp.get("benign_fpr_at_0.5", {})
    mb_all = f.get("modernbert_all")
    mb_mix = f.get("modernbert_mixed_only")
    if not (mb_all and mb_mix):
        return "\\PENDING"
    return (f"A fine-tuned ModernBERT shows the same pattern: trained on all data it flags {pct(mb_all[0], 0)} "
            f"of unseen-source benign skills, and trained on mixed-label sources only {pct(mb_mix[0], 0)}, "
            f"so the shortcut is a property of the data, not of the linear model class.")


if __name__ == "__main__":
    main()
